// Regenerates web/src/core/api-types.ts from the FastAPI OpenAPI schema (no Atlas needed).
import { execFileSync } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const spec = execFileSync(
  'uv',
  ['run', '--quiet', '--directory', 'api', 'python', '-c',
    'import json; from app.main import app; print(json.dumps(app.openapi()))'],
  { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
)
const ast = await openapiTS(JSON.parse(spec))
const out = join(root, 'web/src/core/api-types.ts')
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, `// Generated by \`npm run gen:types\` from FastAPI /openapi.json. Do not edit.\n\n${astToString(ast)}`)
console.log(`wrote ${out}`)
